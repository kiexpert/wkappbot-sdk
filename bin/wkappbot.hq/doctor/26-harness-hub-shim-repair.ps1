# wkdoctor check: harness-hub-shim-repair -- unconditionally repair D:\GitHub hub forwarders
# so a stray delete or BOM can never brick the harness.
# Background: The harness PreToolUse/PostToolUse hooks (in ~/.claude/settings.json) call
# D:\GitHub\wkharness.ps1 and D:\GitHub\wkharness-post.ps1 -- thin 3-line "redirect shims"
# that forward to the canonical body under D:\GitHub\wkappbot-kih\tools\. These must be
# self-healing (no BOM, correct content) or a bad rm/edit breaks every tool call.
# FAIL-OPEN: any error -> ok/na, never crash the doctor.

try {
    $hubPairs = @(
        @{ hub = 'D:\GitHub\wkharness.ps1'; kih = 'D:\GitHub\wkappbot-kih\tools\wkharness.ps1' },
        @{ hub = 'D:\GitHub\wkharness-post.ps1'; kih = 'D:\GitHub\wkappbot-kih\tools\wkharness-post.ps1' }
    )

    $results = @()
    $repaired_list = @()

    foreach ($pair in $hubPairs) {
        $hubPath = $pair.hub
        $kihPath = $pair.kih
        $fileName = (Split-Path -Leaf $hubPath)

        try {
            # Step 1: Check if the kih target file exists
            if (-not (Test-Path -LiteralPath $kihPath)) {
                Add-Check 'harness-hub-shim-repair' 'ok' "! $fileName (canonical missing at $kihPath)"
                Emit '!' 'harness-hub-shim-repair' "! $fileName (canonical missing at $kihPath)"
                $results += "! $fileName"
                continue
            }

            # Step 2: Determine if the hub forwarder is HEALTHY
            # Health check: (file exists) AND (first 3 bytes are NOT UTF-8 BOM ef bb bf) AND (text contains target path)
            $isHealthy = $false
            $hasBom = $false
            $hasPath = $false

            if (Test-Path -LiteralPath $hubPath) {
                # Read first 3 bytes to check for BOM
                try {
                    $bytes = [System.IO.File]::ReadAllBytes($hubPath)
                    if ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF) {
                        $hasBom = $true
                    }
                } catch { }

                # Read text content to check if it references the target path
                try {
                    $content = [System.IO.File]::ReadAllText($hubPath)
                    if ($content -match [regex]::Escape($kihPath)) {
                        $hasPath = $true
                    }
                } catch { }

                # Healthy = file exists AND no BOM AND contains path
                if (-not $hasBom -and $hasPath) {
                    $isHealthy = $true
                }
            }

            # Step 3: If NOT healthy, REPAIR UNCONDITIONALLY
            if (-not $isHealthy) {
                $expectedContent = @"
# redirect shim -- auto-generated by wkdoctor 26-harness-hub-shim-repair
`$input | & powershell -NoProfile -NonInteractive -ExecutionPolicy Bypass -File "$kihPath" @args
exit `$LASTEXITCODE
"@

                try {
                    # Write BOM-free UTF-8 using New-Object System.Text.UTF8Encoding($false)
                    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
                    [System.IO.File]::WriteAllText($hubPath, $expectedContent, $utf8NoBom)

                    Add-Check 'harness-hub-shim-repair' 'ok' "+ $fileName :repaired"
                    Emit 'ok' 'harness-hub-shim-repair' "+ $fileName :repaired"
                    $results += "+ $fileName"
                    $repaired_list += $fileName
                } catch {
                    Add-Check 'harness-hub-shim-repair' 'ok' "! $fileName write failed (fail-open): $_"
                    Emit '!' 'harness-hub-shim-repair' "! $fileName write failed: $_"
                    $results += "! $fileName"
                }
            } else {
                # Step 4: If healthy, emit OK
                Add-Check 'harness-hub-shim-repair' 'ok' "+ $fileName (healthy)"
                Emit '+' 'harness-hub-shim-repair' "+ $fileName (healthy)"
                $results += "+ $fileName"
            }
        } catch {
            Add-Check 'harness-hub-shim-repair' 'ok' "n/a $fileName (check error, fail-open): $_"
            Emit 'ok' 'harness-hub-shim-repair' "n/a $fileName (fail-open)"
            $results += "n/a"
        }
    }

    # Summary emit
    $summary = $results -join ' | '
    if ($repaired_list.Count -gt 0) {
        Emit 'ok' 'harness-hub-shim-repair:summary' "repaired $($repaired_list.Count): $($repaired_list -join ', ') | $summary"
    } else {
        Emit 'ok' 'harness-hub-shim-repair:summary' "all healthy or unavailable: $summary"
    }

} catch {
    Add-Check 'harness-hub-shim-repair' 'ok' "n/a (check error, fail-open): $_"
    Emit 'ok' 'harness-hub-shim-repair' 'n/a (check error, fail-open)'
}
